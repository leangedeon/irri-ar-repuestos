def _parse(text):
    out = {}
    for line in text.strip().splitlines():
        if "=" not in line:
            continue
        en, rest = line.split("=", 1)
        es, kind = rest.rsplit(":", 1)
        out[en.strip().upper()] = (es.strip(), kind.strip())
    return out


