export const DICTS: Record<Locale, Dict> = { es, en };
export const getDict = (l: Locale) => DICTS[l];

export const NUMBER_LOCALE: Record<Locale, string> = { es: 'es-AR', en: 'en-US' };
export const fmt = (l: Locale, n: number, opts?: Intl.NumberFormatOptions) => n.toLocaleString(NUMBER_LOCALE[l], opts);

export function weightLabel(l: Locale, lb: number | null | undefined, qty = 1) {
  if (!lb) return '';
  const kg = lb * 0.4536 * qty;
  if (kg < 1) return `${fmt(l, Math.max(1, Math.round(kg * 1000)))} g`;
  return `${fmt(l, kg, { maximumFractionDigits: kg < 10 ? 2 : 1 })} kg`;
}
